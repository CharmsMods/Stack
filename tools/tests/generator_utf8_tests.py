"""Run affected generators under UTF-8 and a simulated Windows CP932 default.

This checks file encoding and Unicode argv/path handling, not a Windows compiler.
"""
from pathlib import Path
import runpy
import sys
import tempfile
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
GENERATORS = (
    "color_warp_analysis_callback_tests.py", "color_warp_area_owner_tests.py",
    "color_warp_shortcut_tests.py", "gallery_navigator_tests.py",
    "gallery_project_preview_tests.py", "gallery_project_selection_tests.py",
    "gallery_widget_identity_tests.py", "output_card_presentation_tests.py",
    "queue_texture_lifetime_tests.py", "viewport_cursor_overlay_tests.py",
)


def main():
    original_read = Path.read_text
    original_write = Path.write_text
    with tempfile.TemporaryDirectory(prefix="stack-generator-encoding-") as directory:
        outputs = Path(directory) / "\u5199\u771f \u00e9"
        outputs.mkdir()
        for name in GENERATORS:
            results = []
            for default in ("utf-8", "cp932"):
                def locale_read(self, encoding=None, errors=None):
                    return original_read(self, encoding=encoding or default, errors=errors)

                def locale_write(self, data, encoding=None, errors=None):
                    return original_write(self, data, encoding=encoding or default,
                                          errors=errors)

                destination = outputs / (name + "." + default + ".cpp")
                arguments = [str(ROOT / "tools/tests" / name), "--output", str(destination)]
                with patch.object(Path, "read_text", locale_read), \
                        patch.object(Path, "write_text", locale_write), \
                        patch.object(sys, "argv", arguments):
                    runpy.run_path(arguments[0], run_name="__main__")
                results.append(destination.read_bytes())
            if results[0] != results[1]:
                raise AssertionError(f"Locale changed generated bytes: {name}")
    print("Ten generators preserve UTF-8 bytes with CP932 defaults and Unicode output paths.")


if __name__ == "__main__":
    main()
