import os
import tempfile
from io import BytesIO


def write_bytes(out_file, data, trim_line_ends=False):
    for index, byte in enumerate(data):
        if index % 12 == 0:
            out_file.write("\n    ")
        out_file.write(f"0x{byte:02x},")
        if not trim_line_ends or (
            (index + 1) % 12 != 0 and index + 1 != len(data)
        ):
            out_file.write(" ")


def invert_png_rgb(data):
    """Invert an icon at bake time while preserving its alpha channel."""
    from PIL import Image, ImageOps

    with Image.open(BytesIO(data)) as image:
        rgba = image.convert("RGBA")
        red, green, blue, alpha = rgba.split()
        inverted = Image.merge("RGBA", (
            ImageOps.invert(red),
            ImageOps.invert(green),
            ImageOps.invert(blue),
            alpha,
        ))
        output = BytesIO()
        inverted.save(output, format="PNG")
        return output.getvalue()


def make_png_white(data):
    """Convert an icon's RGB channels to white while preserving its alpha channel."""
    from PIL import Image

    with Image.open(BytesIO(data)) as image:
        rgba = image.convert("RGBA")
        red, green, blue, alpha = rgba.split()
        white = Image.new("L", rgba.size, 255)
        white_rgba = Image.merge("RGBA", (white, white, white, alpha))
        output = BytesIO()
        white_rgba.save(output, format="PNG")
        return output.getvalue()


def bake_icons(input_specs, output_path):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    # Write beside the generated header and replace it only after the handle is
    # closed.  MSBuild/antivirus file observation can transiently reject a
    # truncate-open of the existing header on Windows.
    temporary = tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=os.path.dirname(output_path),
        prefix="EmbeddedTabIcons-",
        suffix=".tmp",
        delete=False,
    )
    temporary_path = temporary.name
    try:
        out_file = temporary
        out_file.write("#pragma once\n\n")
        out_file.write("// This file is automatically generated. Do not edit manually.\n\n")
        out_file.write("namespace EmbeddedTabIcons {\n\n")

        for symbol_name, input_path, *transforms in input_specs:
            data = b""
            if os.path.exists(input_path):
                try:
                    with open(input_path, "rb") as icon_file:
                        data = icon_file.read()
                    if "invert" in transforms:
                        data = invert_png_rgb(data)
                    if "white" in transforms:
                        data = make_png_white(data)
                except OSError as exc:
                    print(f"Warning: Could not read {input_path}: {exc}")
            else:
                print(f"Bake Notice: No tab icon found at {input_path}. Writing fallback bytes.")

            out_file.write(f"inline const unsigned char {symbol_name}_png_data[] = {{")
            if data:
                write_bytes(out_file, data, symbol_name.startswith(("File", "Library", "Graph")))
            else:
                out_file.write("\n    0x00")
            out_file.write("\n};\n\n")
            out_file.write(f"inline const unsigned int {symbol_name}_png_size = {len(data)};\n\n")

        out_file.write("} // namespace EmbeddedTabIcons\n")
        out_file.close()
        os.replace(temporary_path, output_path)
    except Exception:
        temporary.close()
        try:
            os.remove(temporary_path)
        except OSError:
            pass
        raise


